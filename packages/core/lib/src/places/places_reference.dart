/// Lieux de [places] dont le nom contient [query], sans tenir compte des accents, de la casse ni des
/// séparateurs (« san ped » trouve « San-Pédro », « mbahiakro » trouve « M'Bahiakro »).
List<String> searchPlaces(Iterable<String> places, String query) {
  String key(String text) =>
      foldAccents(text).replaceAll(RegExp(r"[\s\-']"), '');
  final q = key(query);
  return q.isEmpty
      ? places.toList()
      : [
          for (final p in places)
            if (key(p).contains(q)) p,
        ];
}
